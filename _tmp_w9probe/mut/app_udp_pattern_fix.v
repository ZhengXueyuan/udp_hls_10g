    wire        gen_ok  = (txs == T_FRM) && !txf_full_n && !nul_pend &&
                          (seg_sent < seg_len);
    // 本拍产出的字节正好凑齐本字 ⇒ 同拍推入 FIFO (零气泡: 无独立"呈交"拍)
    wire        push_now = gen_ok && ((bcnt + 4'd1) >= need);
    // 帧收尾 (末字已推入 FIFO) —— 帧计数/限速/done 判定的唯一落点 (P5f: 推送侧)
    wire        nul_push = (txs == T_FRM) && nul_pend && !txf_full_n;
`ifdef P7B_10G
    // =====================================================================
    // 8 字节/拍 TX (P7B_10G): 剩余 >= 8 字节时**一拍推一个满字**; 剩 < 8 的
    // **尾字**自动落到下面的逐字节路径 ⇒ 非 8 倍数载荷结构性正确 (含 PLEN_MAX
    // 冻结 + 0xA5 填充, 与逐字节路径同款)。
    // 逐字节恒等: gen_word 的 lane k = (M^k·s)[31:24] = 序列第 k 个字节;
    //   tx_lfsr_8 = M^8·s = 推进 8 步 ⇒ 与「每拍 1 字节」序列**同一个流**。
    // =====================================================================
    wire [63:0] tx_lfsr_8 = xs_next8(tx_lfsr);              // 状态推进 8 步
    wire [63:0] gen_word  = pay_ok ? xs_word8(tx_lfsr)      // 8 个字节 (lane0 在前)
                                  : 64'hA5A5A5A5A5A5A5A5;
    // 满字快路径: gen_ok 已含 (T_FRM && !txf_full && !nul_pend && 未发完)
    wire        wide_ok   = gen_ok && (left >= 12'd8);
`endif
`ifdef P7B_10G
    wire        frm_close = (push_now || wide_ok) ? last_b : nul_push;
`else
    wire        frm_close = push_now ? last_b : nul_push;
`endif
    wire        push_any  = push_now || nul_push;

    //=========================================================================
    // RX 侧: 字节串行逐字节比对, 1 字前瞻寄存器 ⇒ 8 字节恰 8 拍 (II=1 无缝)
    //=========================================================================
    reg  [63:0] rx_lfsr;
    reg  [63:0] cmp_d;   reg [7:0] cmp_k;  reg [3:0] cmp_n, cmp_i;  reg cmp_busy;
    reg  [63:0] nx_d;    reg [7:0] nx_k;   reg [3:0] nx_n;          reg nx_v;

`ifdef RXP_DIAG
    // 首失配快照的内部状态 (端口是 output wire, 这里驱动)
    reg  [31:0] ds_idx_r, ds_b1_r, ds_b2_r, ds_bg_r, ds_dup_r;
    reg  [7:0]  ds_got_r, ds_exp_r, ds_prev_r;
    reg         ds_v_r;
    reg  [7:0]  ds_prev_exp;             // 上一拍比对的期望字节
    // ---- v2 (2026-09-26): 整字指纹 + 帧内偏移桶 ----
    reg  [63:0] ds_gw_r, ds_ew_r;        // 首失配所在整字 (收/期望, 同一边界)
    reg  [31:0] ds_oz_r, ds_ol_r, ds_om_r, ds_oh_r;
    reg  [63:0] wr_e_r;                  // 本收字的期望字节累加 (按 lane 固定位置写)
    reg  [11:0] off_cnt;                 // 帧内偏移 (mod i_paylen); 语义见下 off_eff
    reg         nx_sf, cmp_sf;           // SOF 与数据**同管线**的伴随位 (1 字前瞻)
    reg         cap_pend;                // 本字含首失配 ⇒ 字尾取整字快照
    assign ds_idx = ds_idx_r;
    assign ds_b1  = ds_b1_r;   assign ds_b2   = ds_b2_r;   assign ds_bg  = ds_bg_r;
    assign ds_dup = ds_dup_r;  assign ds_got  = ds_got_r;  assign ds_exp = ds_exp_r;
    assign ds_prev= ds_prev_r; assign ds_v    = ds_v_r;
    assign ds_gw  = ds_gw_r;   assign ds_ew   = ds_ew_r;
    assign ds_oz  = ds_oz_r;   assign ds_ol   = ds_ol_r;
    assign ds_om  = ds_om_r;   assign ds_oh   = ds_oh_r;
`else
    assign ds_idx = 32'd0;
    assign ds_b1  = 32'd0; assign ds_b2  = 32'd0; assign ds_bg  = 32'd0;
    assign ds_dup = 32'd0; assign ds_got = 8'd0;  assign ds_exp = 8'd0;
    assign ds_prev= 8'd0;  assign ds_v   = 1'b0;
    assign ds_gw  = 64'd0; assign ds_ew  = 64'd0;
    assign ds_oz  = 32'd0; assign ds_ol  = 32'd0;
    assign ds_om  = 32'd0; assign ds_oh  = 32'd0;
`endif

    // 前瞻空即收: 引擎比对 8 拍期间恰好等下一次装载 ⇒ 稳态 1 字节/拍
`ifdef P7B_10G
    // 宽路径的 rx_tready 定义在下面的 8 路块里 (要用到 cmp_ld_w)
`else
    assign rx_tready = !nx_v;
`endif

    wire [7:0] rx_exp  = rx_lfsr[31:24];
    wire [7:0] rx_got  = byte_at(cmp_d, cmp_i);
    wire       cmp_hit = cmp_busy && (cmp_n != 4'd0);          // 本拍真比一个字节
    wire       cmp_end = (cmp_i + 4'd1 >= cmp_n);              // 本拍比的是本字末字节
    wire       rx_bad  = cmp_hit && i_en && (rx_got !== rx_exp);
    wire       rx_ld   = rx_tvalid && rx_tready;               // 前瞻装载
`ifdef P7B_10G
    // =====================================================================
    // 8 字节/拍 RX 校验 (P7B_10G): 满字**一拍比完**; 非满字(尾字/0 长帧)仍走
    // 上面的逐字节路径 ⇒ 非 8 倍数帧结构性正确。
    // 期望序列与 TX 侧**同一组映射** (xs_word8) ⇒ 两侧同源, 不会各自近似。
    // =====================================================================
`ifdef RXP_DIAG
    // 诊断构建 (RXP_DIAG) 的 v1-v4 仪器全是**逐字节量** (ds_idx 活计数器 /
    // 帧内偏移桶 / 事件 FIFO), 与满字并行比对不兼容 ⇒ 该组合下宽 RX 关闭
    // (退回逐字节: 正确但慢)。⚠️ 目前没有任何构建同时开这两个宏。
    wire        wide_cmp = 1'b0;
    wire [63:0] rx_lfsr_8   = 64'd0;   // 哑声明 (下方 always 里的分支恒假, 不进网表)
    wire [3:0]  rx_bad_n    = 4'd0;
    assign rx_tready = !nx_v;
`else
    wire [63:0] rx_exp_word = xs_word8(rx_lfsr);      // 本字 8 个期望字节
    wire [63:0] rx_lfsr_8   = xs_next8(rx_lfsr);      // 期望序列推进 8 步
    // 只在「满字 && 在本字首字节」时成立; 一旦非满字, 结构性退回逐字节路径
    wire        wide_cmp    = cmp_busy && (cmp_n == 4'd8) && (cmp_i == 4'd0);
    wire [7:0]  rx_bad_v;                             // 逐 lane 失配 (i_en=0 恒 0)
    assign rx_bad_v[0] = i_en && (cmp_d[63:56] !== rx_exp_word[63:56]);
    assign rx_bad_v[1] = i_en && (cmp_d[55:48] !== rx_exp_word[55:48]);
    assign rx_bad_v[2] = i_en && (cmp_d[47:40] !== rx_exp_word[47:40]);
    assign rx_bad_v[3] = i_en && (cmp_d[39:32] !== rx_exp_word[39:32]);
    assign rx_bad_v[4] = i_en && (cmp_d[31:24] !== rx_exp_word[31:24]);
    assign rx_bad_v[5] = i_en && (cmp_d[23:16] !== rx_exp_word[23:16]);
    assign rx_bad_v[6] = i_en && (cmp_d[15:8]  !== rx_exp_word[15:8]);
    assign rx_bad_v[7] = i_en && (cmp_d[7:0]   !== rx_exp_word[7:0]);
    wire [3:0]  rx_bad_n = pop8(rx_bad_v);            // 本拍失配字节数 (0..8)
    // cmp 寄存器的装载条件 (语义与 diag 段那条 cmp_ld 相同, 但不引 cmp_end 线:
    // 本块在它之前 —— 坑 22: xvlog 先声明后用)
    wire        cmp_ld_w = nx_v && (!cmp_busy || (cmp_n == 4'd0) ||
                                    (cmp_i + 4'd1 >= cmp_n) || wide_cmp);
    // 宽路径 1 字/拍: 前瞻字被**消费的同拍**必须能再收一个字, 否则每字 2 拍
    // (只到 4 字节/拍)。串行路径下它只是把手递提前 1 拍 (nx 寄存器同拍被
    // 读走+写新 ⇒ 无覆盖, 无丢字), 逻辑等价。
    assign rx_tready = !nx_v || cmp_ld_w;
`endif
`endif

`ifdef RXP_DIAG
    // popcount(got^exp) 形状分类 (声明必须在 rx_got/rx_exp 之后 —— 坑 22:
    // xvlog 先声明后用, 放前面会报 "identifier is used before its declaration")
    function [3:0] pc8;
        input [7:0] v;
        integer i;
        reg [3:0] c;
        begin
            c = 4'd0;
            for (i = 0; i < 8; i = i + 1) c = c + {3'b0, v[i]};
            pc8 = c;
        end
    endfunction
    wire [3:0] ds_pcn = pc8(rx_got ^ rx_exp);

    // ---- v2: 整字指纹 + 帧内偏移桶 (纯组合部分; 全部只在 RXP_DIAG 里存在) ----
    // 把 8 位字节放到 lane i (lane0 = [63:56], 同 byte_at()); 其余 lane 为 0。
    // 用来补上"本拍正在比对的 lane"—— 该 lane 本拍还没写进 wr_e_r 寄存器。
    function [63:0] put8_0;
        input [3:0] i;
        input [7:0] b;
        begin
            case (i)
                4'd0: put8_0 = {b,    56'd0};
                4'd1: put8_0 = {8'd0,  b, 48'd0};
                4'd2: put8_0 = {16'd0, b, 40'd0};
                4'd3: put8_0 = {24'd0, b, 32'd0};
                4'd4: put8_0 = {32'd0, b, 24'd0};
                4'd5: put8_0 = {40'd0, b, 16'd0};
                4'd6: put8_0 = {48'd0, b, 8'd0};
                default: put8_0 = {56'd0, b};
            endcase
        end
    endfunction

    // lane 掩码: 低 n 个 lane (lane0 在 [63:56]) 全 1, 其余 0。
    // 用 cmp_n (而非 tkeep) 与引擎的比对口径**逐位一致** (引擎按 popcount 比对)。
    function [63:0] bm64;
        input [3:0] n;
        begin
            case (n)
                4'd0: bm64 = 64'h0000_0000_0000_0000;
                4'd1: bm64 = 64'hFF00_0000_0000_0000;
                4'd2: bm64 = 64'hFFFF_0000_0000_0000;
                4'd3: bm64 = 64'hFFFF_FF00_0000_0000;
                4'd4: bm64 = 64'hFFFF_FFFF_0000_0000;
                4'd5: bm64 = 64'hFFFF_FFFF_FF00_0000;
                4'd6: bm64 = 64'hFFFF_FFFF_FFFF_0000;
                4'd7: bm64 = 64'hFFFF_FFFF_FFFF_FF00;
                default: bm64 = 64'hFFFF_FFFF_FFFF_FFFF;
            endcase
        end
    endfunction

    // 前瞻寄存器 nx_* → 比对寄存器 cmp_* 的**装载拍** (与下面 always 里那三处
    // 装载分支逐一对应: 空闲装载 / 空拍装载 / 字末装载)。rx_ld 与 cmp_ld 结构上
    // 互斥 (rx_ld 要求 !nx_v, 而 cmp_ld 三支都要求 nx_v)。
    wire        cmp_ld  = nx_v && (!cmp_busy || (cmp_n == 4'd0) || cmp_end);
    wire        wr_end  = cmp_hit && cmp_end;              // 本字最后一个字节的比对拍
    // 本拍比的是**帧首字节** (SOF 与数据同管线, 故 cmp_sf 就是"本字含帧首字节")
    wire        off_rst = cmp_hit && cmp_sf && (cmp_i == 4'd0);
    // 本拍字节的帧内偏移 = 计数器当前值; 帧首字节拍**组合地**取 0 —— 寄存器要到
    // 本拍才被复位, 直接读 off_cnt 会把上一帧末尾的值 (如 1471) 当成本字节的偏移。
    wire [11:0] off_eff = off_rst ? 12'd0 : off_cnt;
    // 本字期望整字: 累加器 + 本拍 lane (OR 安全 —— 本 lane 在字内尚未被写过, 恒 0)
    wire [63:0] ds_wr_e_now = wr_e_r | put8_0(cmp_i, rx_exp);

    // 帧内偏移桶 (if/else-if 链 ⇒ 每次失配恰进一桶 ⇒ OZ+OL+OM+OH == UMM 恒成立)。
    // 第 4 桶 = 兜底 (off_eff >= paylen-1 且 >= 64 的一切情形), 边界: 0 / 1..7 /
    // 8..63 / >=64。
    wire        ds_bo0 = (off_eff == 12'd0);
    wire        ds_bo1 = (off_eff >= 12'd1)  && (off_eff <= 12'd7);
    wire        ds_bo2 = (off_eff >= 12'd8)  && (off_eff <= 12'd63);

    // v3: 首失配触发脉冲 —— 与下面 always 里取整字快照的那个 if 条件**逐字相同**
    // (所以"ds_cap 那一拍"与"ds_gw/ds_ew 被写入的那一拍"定义上就是同一拍)。
    assign ds_cap = wr_end && (cap_pend || (rx_bad && !ds_v_r));

    // ---- v4: 运行结构 + 事件 FIFO 的状态 (声明必须先于下面那个 always —— 坑 22) ----
    reg  [15:0] fi_cnt;          // 已开始的帧数 (= 下一个帧号); 帧首字装载拍 +1
    reg  [15:0] nx_fi, cmp_fi;   // 随数据走 1 字前瞻管线的帧号 (装载拍 / 比对拍)
    reg  [15:0] fi_last;         // 上一个受损帧的帧号 (连续段判据)
    reg  [15:0] cur_run;         // 当前连续段长度
    reg         ev_seen;         // 已发生过至少一个事件
    reg  [23:0] ev_f [0:7];      // 事件 FIFO: {帧号[23:8], got[7:0]}, 只入不出
    integer     v4_i;            // ev_f 复位用
    // 事件 = 偏移 0 的失配字节 (与 v2 的 OZ 桶条件 ds_bo0 逐字相同 ⇒ NE == OZ)
    wire        v4_evt = rx_bad && ds_bo0;
    assign v4_ea = ev_f[0];  assign v4_eb = ev_f[1];
    assign v4_ec = ev_f[2];  assign v4_ed = ev_f[3];
    assign v4_ee = ev_f[4];  assign v4_ef = ev_f[5];
    assign v4_eg = ev_f[6];  assign v4_eh = ev_f[7];
`endif

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            txs <= T_IDLE; tx_lfsr <= SEED;
            seg_len <= 12'd0; seg_sent <= 12'd0; bcnt <= 4'd0; stg <= 64'd0;
            txf_in <= 73'd0; txf_wr <= 1'b0;
            nul_pend <= 1'b0; gap_cnt <= 16'd0; remain <= 32'd0;
            first_frm <= 1'b1;
            stat_tx_bytes <= 32'd0; stat_tx_frames <= 32'd0;
            active <= 1'b0; done <= 1'b0;
            rx_lfsr <= SEED;
            cmp_d <= 64'd0; cmp_k <= 8'h00; cmp_n <= 4'd0; cmp_i <= 4'd0;
            cmp_busy <= 1'b0;
            nx_d <= 64'd0; nx_k <= 8'h00; nx_n <= 4'd0; nx_v <= 1'b0;
            stat_rx_bytes <= 32'd0; stat_rx_frames <= 32'd0;
            stat_rx_null <= 32'd0; stat_mismatch <= 32'd0;
            led <= 4'd0;
`ifdef RXP_DIAG
            ds_idx_r <= 32'd0;
            ds_b1_r <= 32'd0; ds_b2_r <= 32'd0; ds_bg_r <= 32'd0; ds_dup_r <= 32'd0;
            ds_got_r <= 8'd0; ds_exp_r <= 8'd0; ds_prev_r <= 8'd0;
            ds_v_r <= 1'b0; ds_prev_exp <= 8'd0;
            ds_gw_r <= 64'd0; ds_ew_r <= 64'd0; wr_e_r <= 64'd0;
            ds_oz_r <= 32'd0; ds_ol_r <= 32'd0;
            ds_om_r <= 32'd0; ds_oh_r <= 32'd0;
            off_cnt <= 12'd0; nx_sf <= 1'b0; cmp_sf <= 1'b0; cap_pend <= 1'b0;
            // v4: 运行结构 + 事件 FIFO (未用条目恒 0 —— FIFO 只入不出, 不回绕)
            v4_ne <= 16'd0; v4_nr <= 16'd0; v4_mr <= 16'd0;
            v4_en <= 4'd0;  v4_eo <= 1'b0;
            fi_cnt <= 16'd0; nx_fi <= 16'd0; cmp_fi <= 16'd0;
            fi_last <= 16'd0; cur_run <= 16'd0; ev_seen <= 1'b0;
            for (v4_i = 0; v4_i < 8; v4_i = v4_i + 1) ev_f[v4_i] <= 24'd0;
`endif
        end else begin
            //=================================================================
            // TX FSM
            //=================================================================
            txf_wr <= 1'b0;          // 脉冲型: 每拍默认清零 (坑 6)
            case (txs)
                T_IDLE: begin
                    // 默认不激活: i_en=0 (未使能) 或 i_tx_ready=0 (peer 表空 =
                    // 未 learn-on-RX) ⇒ 停在这里, m_tvalid 恒 0 ⇒ 下游看不到帧,
                    // 线上零新增 (与 T2 的默认不发送逐位一致)。
                    if (i_en && i_tx_ready) begin
                        seg_len   <= seg_len_n;
                        seg_sent  <= 12'd0;
                        bcnt      <= 4'd0;
                        stg       <= 64'd0;
                        nul_pend  <= (seg_len_n == 12'd0);  // 0 长数据报: 单拍收尾
                        remain    <= rem_eff;              // 首帧 = TX_BYTES, 之后不动
                        first_frm <= 1'b0;
                        txs       <= T_FRM;
                    end
                end
                T_FRM: begin
                    // 0 长数据报: 推 1 拍 {tkeep=0, tlast=1}
                    // (udp_tx_frame 的 wr 只按 tkeep!=0 ⇒ plen=0 ⇒ 线上 42+8
                    //  字节的合法空数据报; 与 peer --udp-paylen 0 语义一致)
`ifdef P7B_10G
                    if (wide_ok) begin
                        // 一拍推 8 字节 (need 恒 8; last_b = (left == 8) 即本帧末字)
                        txf_wr        <= 1'b1;
                        txf_in        <= {last_b, 8'hFF, gen_word};
                        seg_sent      <= seg_sent + 12'd8;
                        stat_tx_bytes <= stat_tx_bytes + 32'd8;
                        remain        <= rem_n;
                        bcnt          <= 4'd0;
                        stg           <= 64'd0;
                        if (pay_ok) tx_lfsr <= tx_lfsr_8;   // 超长帧冻结 (同逐字节)
                    end else
`endif
                    if (nul_push) begin
                        txf_wr <= 1'b1;
                        txf_in <= {1'b1, 8'h00, 64'd0};
                    end else if (gen_ok) begin
                        // 产 1 字节 (先取后推进 —— 与 peer/app_pattern 同款;
                        // 超长帧冻结 LFSR, 见 pay_ok)
                        if (push_now) begin
                            // 本字节凑齐本字 ⇒ **同拍推入** (无独立"呈交"拍)
                            txf_wr        <= 1'b1;
                            txf_in        <= {last_b, kmask8(need),
                                              ljust8({stg[55:0], gen_byte}, need)};
                            seg_sent      <= seg_sent + {8'b0, need};
                            stat_tx_bytes <= stat_tx_bytes + {28'b0, need};
                            remain        <= rem_n;
                            bcnt          <= 4'd0;
                            stg           <= 64'd0;
                        end else begin
                            bcnt <= bcnt + 4'd1;
                            stg  <= {stg[55:0], gen_byte};
                        end
                        if (pay_ok) tx_lfsr <= xs_next(tx_lfsr);
                    end
                    // 帧收尾: 计数/限速/done (推送侧, 见头注释)
                    if (frm_close) begin
                        stat_tx_frames <= stat_tx_frames + 32'd1;
                        gap_cnt        <= TX_GAP;
                        if (TX_BYTES != 32'd0 && rem_n == 32'd0) begin
                            txs  <= T_DONE;
                            done <= 1'b1;
                        end else begin
                            txs <= T_GAP;
                        end
                    end
                end
                T_GAP: begin
                    // 限速: TX_GAP 个空闲拍后才允许下一帧 (TX_GAP=0 ⇒ 下拍即下一帧)
                    if (gap_cnt != 16'd0) gap_cnt <= gap_cnt - 16'd1;
                    else                  txs     <= T_IDLE;
                end
                default: begin   // T_DONE: 粘滞, 只有复位才能再开
                    txs <= T_DONE;
                end
            endcase

            // active: 发帧中 或 帧间限速间隙 (板级 LED "有会话" 语义)
            active <= (txs == T_FRM) || (txs == T_GAP);

            //=================================================================
            // RX 引擎 (装载与比对并行)
            //=================================================================
`ifdef P7B_10G
            // ⚠️ 宽路径 (P7B_10G): rx_tready = !nx_v || cmp_ld_w ⇒ 上面那条「结构性互斥」
            //    已被**有意**放宽 (否则每个字要 2 拍 = 4 字节/拍)。代价是下面三处
            //    消费分支的 nx_v 必须写成 rx_ld —— 否则同拍新装进来的字被静默丢弃
            //    (实测症状: 回环只收到一半字节)。
`endif
            // 装载 (前瞻空位才有 rx_tready ⇒ 与下面的"消费 nx"结构性互斥)
            if (rx_ld) begin
                nx_d <= rx_tdata;
                nx_k <= rx_tkeep;
                nx_n <= pop8(rx_tkeep);
                nx_v <= 1'b1;
            end
            if (cmp_busy) begin
                // 比对 cmp_i 字节 (组合 rx_bad) + 推进/收字
                if (cmp_n == 4'd0) begin
                    // 空拍 (0 长数据报的合成拍, 或 tkeep=0): 无字节可比, 1 拍收
                    if (nx_v) begin
                        cmp_d <= nx_d; cmp_k <= nx_k; cmp_n <= nx_n; cmp_i <= 4'd0;
`ifdef P7B_10G
                        nx_v  <= rx_ld;    // 同拍消费+装载: 新字必须留下
`else
                        nx_v  <= 1'b0;
`endif
                    end else begin
                        cmp_busy <= 1'b0;
                    end
`ifdef P7B_10G
                end else if (cmp_end || wide_cmp) begin
`else
                end else if (cmp_end) begin
`endif
                    if (nx_v) begin
                        cmp_d <= nx_d; cmp_k <= nx_k; cmp_n <= nx_n; cmp_i <= 4'd0;
`ifdef P7B_10G
                        nx_v  <= rx_ld;    // 同拍消费+装载: 新字必须留下
`else
                        nx_v  <= 1'b0;
`endif
                    end else begin
                        cmp_busy <= 1'b0;
                    end
                end else begin
                    cmp_i <= cmp_i + 4'd1;
                end
            end else if (nx_v) begin
                cmp_d <= nx_d; cmp_k <= nx_k; cmp_n <= nx_n; cmp_i <= 4'd0;
`ifdef P7B_10G
                cmp_busy <= 1'b1; nx_v <= rx_ld;   // 同拍消费+装载: 新字必须留下
`else
                cmp_busy <= 1'b1; nx_v <= 1'b0;
`endif
            end
            // 期望序列: 未使能 ⇒ 钉 SEED (不校验); 使能 ⇒ 每比一个字节推进 1 步
`ifdef P7B_10G
            if (!i_en)               rx_lfsr <= SEED;
            else if (wide_cmp)       rx_lfsr <= rx_lfsr_8;
            else if (cmp_hit)        rx_lfsr <= xs_next(rx_lfsr);
`else
            if (!i_en)               rx_lfsr <= SEED;
            else if (cmp_hit)        rx_lfsr <= xs_next(rx_lfsr);
`endif
            // 统计
`ifdef P7B_10G
            if (wide_cmp)       stat_rx_bytes <= stat_rx_bytes + 32'd8;
            else if (cmp_hit)   stat_rx_bytes <= stat_rx_bytes + 32'd1;
`else
            if (cmp_hit)        stat_rx_bytes <= stat_rx_bytes + 32'd1;
`endif
`ifdef P7B_10G
            if (wide_cmp)       stat_mismatch <= stat_mismatch + {28'b0, rx_bad_n};
            else if (rx_bad)    stat_mismatch <= stat_mismatch + 32'd1;
`else
            if (rx_bad)         stat_mismatch <= stat_mismatch + 32'd1;
`endif
            if (rx_ld && rx_sof) begin
                stat_rx_frames <= stat_rx_frames + 32'd1;
                if (rx_len == 16'd0) stat_rx_null <= stat_rx_null + 32'd1;
            end

`ifdef RXP_DIAG
            // ---- 首失配快照 + 形状分类 (RXP_DIAG) ----
            // ds_prev_exp 必须**只在真比对了一字节的拍跟拍** (cmp_hit 同门)。
            // 若无条件跟拍, 则 RX 引擎在帧间/空拍停顿后 (cmp_busy 掉 → 下一帧
            // 首字节) 读到的 ds_prev 会等于 ds_exp 而不是上一个字节 —— 而
            // udp_split 的播放器是**帧级 store-and-forward** (帧间 tvalid 必低)
            // ⇒ **每帧首字节必然踩这个洞**, 而"每帧首字节"恰恰是 u_uf 陈旧写
            // 假设最看重的字节。独立审查 agent 用隔帧 TB 实测复现:
            // 隔帧时 prev=exp (错), 背靠背时 prev=上一字节 (对)。
            if (cmp_hit) ds_prev_exp <= rx_exp;
            if (rx_bad) begin
                if (!ds_v_r) begin
                    // stat_rx_bytes 本拍尚未 +1 ⇒ 正是本字节的全局序号 (= 图案流偏移)
                    ds_v_r   <= 1'b1;
                    ds_idx_r <= stat_rx_bytes;
                    ds_got_r <= rx_got;
                    ds_exp_r <= rx_exp;
                    ds_prev_r<= ds_prev_exp;
                    cap_pend <= 1'b1;      // v2: 首失配落在本字 ⇒ 字尾取整字
                end
                if      (ds_pcn == 4'd1) ds_b1_r <= ds_b1_r + 32'd1;
                else if (ds_pcn == 4'd2) ds_b2_r <= ds_b2_r + 32'd1;
                else                     ds_bg_r <= ds_bg_r + 32'd1;
                if (rx_got == ds_prev_exp) ds_dup_r <= ds_dup_r + 32'd1;
                // ---- v2: 帧内偏移桶 (每次失配恰进一桶; 与 stat_mismatch 同门) ----
                if      (ds_bo0) ds_oz_r <= ds_oz_r + 32'd1;
                else if (ds_bo1) ds_ol_r <= ds_ol_r + 32'd1;
                else if (ds_bo2) ds_om_r <= ds_om_r + 32'd1;
                else             ds_oh_r <= ds_oh_r + 32'd1;
            end

            // ---- v2: SOF 与数据同 1 字前瞻管线 (nx_sf → cmp_sf) ----
            // 帧首字节的判据必须是 cmp_sf (跟着**数据**走的那一位), 不能用 rx_ld 拍
            // 的 rx_sof —— 那正是 v1 活计数器滞后 7 字节的病因 (rx_ld 比该字被比对
            // 早 1 字还多)。
            if (rx_ld)  nx_sf  <= rx_sof;
            if (cmp_ld) cmp_sf <= nx_sf;

            // ---- v2: 帧内偏移计数 (mod i_paylen) ----
            // 与 stat_rx_bytes 同一个事件 (cmp_hit)、同一拍推进 ⇒ off_eff 恒等于
            // "本拍字节的全局序号 mod i_paylen"; 再叠加**帧首字节拍复位** (off_rst)
            // ⇒ 帧长 != i_paylen 时给出的仍是真正的帧内偏移 (门的相 5 判别性用例:
            // 帧长 40 / i_paylen 64, 全局取模会把帧首字节判成 OM, 本实现判成 OZ)。
            // 帧长 > i_paylen ⇒ mod i_paylen 环绕 (由门的相 6 钉死)。
            if (cmp_hit) begin
                if (off_eff == (i_paylen - 12'd1)) off_cnt <= 12'd0;
                else                               off_cnt <= off_eff + 12'd1;
            end

            // ---- v2: 期望字节累加 (lane 固定位置写; cmp_i 在字内单调递增) ----
            // 字装载拍清零 ⇒ 帧末字 (cmp_n<8) 的无效 lane 恒 0, 与 ds_gw 的掩码同口径。
            if (cmp_ld) wr_e_r <= 64'd0;
            else if (cmp_hit) begin
                case (cmp_i)
                    4'd0: wr_e_r[63:56] <= rx_exp;
                    4'd1: wr_e_r[55:48] <= rx_exp;
                    4'd2: wr_e_r[47:40] <= rx_exp;
                    4'd3: wr_e_r[39:32] <= rx_exp;
                    4'd4: wr_e_r[31:24] <= rx_exp;
                    4'd5: wr_e_r[23:16] <= rx_exp;
                    4'd6: wr_e_r[15:8]  <= rx_exp;
                    default: wr_e_r[7:0] <= rx_exp;
                endcase
            end

            // ---- v2: 字尾整字快照 (只对"含首失配的那个字"取一次) ----
            // cap_now 必须**组合地**带上"本拍才刚判出首失配"(失配就在本字末 lane 的
            // 情形): 那时 cap_pend 寄存器还是 0, 只读寄存器会漏掉这个字。
            // cmp_d 在本拍仍是本字 (下一字要到本拍沿上才装载);
            // ds_ew 用 ds_wr_e_now (累加器 + 本拍 lane 的组合补齐)。
            // cap_pend 的清位写在**后面** ⇒ 与同一拍的置位冲突时以清位为准 (该拍
            // 已按 cap_now 取过快照, 正是要清)。两个分支的先后顺序不能调。
            if (wr_end && (cap_pend || (rx_bad && !ds_v_r))) begin
                ds_gw_r  <= cmp_d & bm64(cmp_n);
                ds_ew_r  <= ds_wr_e_now;
                cap_pend <= 1'b0;
            end

            //-----------------------------------------------------------------
            // v4: 受损帧**运行结构** (n_run / max_run) + **事件 FIFO** (前 8 条)
            //-----------------------------------------------------------------
            // 【事件定义】= "首失配落在帧内偏移 0" 的那一拍:
            //     v4_evt = rx_bad && (off_eff == 0)
            //   off_eff 与 v2 的 OZ 桶条件是**同一个表达式** ⇒ 每个 OZ 计数的字节
            //   恰是本仪器的一个事件 ⇒ 门里断言 NE == OZ (两条独立路径互证)。
            //   (整帧被替换时, 每帧只有字节 0 落在偏移 0 ⇒ 每受损帧恰 1 个事件。)
            // 【帧号】与数据同 1 字前瞻管线: fi_cnt 在**帧首字装载拍** +1, 而
            //   nx_fi 在同一拍取 +1 **之前**的值 ⇒ 该字携带的正是它所属的帧号;
            //   cmp_fi 再跟一拍到比对寄存器。故事件拍读到的 cmp_fi = 该字节的帧号。
            //   帧号从 0 起 (与 II/paylen 离线对账)。
            // 【运行结构】相邻事件帧号差 1 ⇒ 同一极大连续段 (cur_run++), 否则新段
            //   (n_run++); max_run 取所有段的长度上界。
            // 【FIFO】8 深, 每条 {帧号[15:0], got[7:0]} = 24 位。**满了之后只计数
            //   不再入队**, 并把 EO 置 1 (粘滞) 明示"有事件未记录" —— 不静默丢弃。
            //   未使用的条目恒 0 (靠复位, 运行中不回绕)。
            if (rx_ld)           nx_fi  <= fi_cnt;
            if (cmp_ld)          cmp_fi <= nx_fi;
            if (rx_ld && rx_sof) fi_cnt  <= fi_cnt + 16'd1;
            if (v4_evt) begin
                v4_ne <= v4_ne + 16'd1;
                if (v4_en != 4'd8) begin
                    ev_f[v4_en] <= {cmp_fi, rx_got};
                    v4_en <= v4_en + 4'd1;
                end else begin
                    v4_eo <= 1'b1;
                end
                if (!ev_seen) begin
                    ev_seen <= 1'b1;
                    v4_nr   <= 16'd1;
                    cur_run <= 16'd1;
                    v4_mr   <= 16'd1;
                end else if (cmp_fi == (fi_last + 16'd1)) begin
                    cur_run <= cur_run + 16'd1;
                    if ((cur_run + 16'd1) > v4_mr) v4_mr <= cur_run + 16'd1;
                end else begin
                    v4_nr   <= v4_nr + 16'd1;
                    cur_run <= 16'd1;
                end
                fi_last <= cmp_fi;
            end
`endif

            //=================================================================
            // LED (板级可观测): d0 = 曾见 peer (i_tx_ready 锁存)
            //                    d1 = 有活动 (收发)
            //                    d2 = 失配粘滞
            //                    d3 = TX 会话在跑 / 已发完
            //=================================================================
            led[0] <= (led[0] || i_tx_ready);
            led[1] <= (cmp_hit || txf_rd);
            if (stat_mismatch != 32'd0) led[2] <= 1'b1;
            led[3] <= (active || done);
        end
    end
endmodule
