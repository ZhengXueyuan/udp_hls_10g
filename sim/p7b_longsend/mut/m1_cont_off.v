                    // P5e: 未落地的载荷字必须撤 (seg_sent==0 的换流路径下它可能正
                    //   摊在呈交口): 它没被计数过、pipe 也没装载 (装载即计数) ⇒
                    //   撤回不丢字节、不破坏 AXIS 数据 (下游只看 s_ready 拍)。
                    pw_valid <= 1'b0;
                    op_pend  <= 1'b1;   // 新会话首帧同样以 opener 起
                    op_sent  <= 1'b0;
                    // P5e: 撞车拍 (本拍同时闭合旧帧: close_send 的 0 载荷收尾字
                    // 已交付) 的帧计数不能漏 (W3 块已让位给本次换流)。
                    if (rst_close && m_tready)
                        stat_tx_frames <= stat_tx_frames + 32'd1;
                    // P5d-D2: `done` 不再被新会话清 0 —— 语义是"app 至少跑完过
                    // 一轮" (checker 原话"app 未跑完一轮"), 逐会话清零会让
                    // "最后一段是 abort/拆连"的正常场景误报未完成。
                    // (默认单会话门: 只有一次 ev_up ⇒ 与旧行为逐位相同)
                    frm_wait <= 1'b0;
                    closing  <= 1'b0;
                    // 首帧长度即刻就位 (否则 asm_go 看到 seg_len=0 直接收帧)
                    seg_len  <= (TX_BYTES > {20'b0, TX_SEGSZ}) ? TX_SEGSZ :
                                TX_BYTES[11:0];
                    seg_sent <= 12'd0;
                    bcnt     <= 4'd0;
                    stg      <= 64'd0;
                    // ⭐ P7B-GAP9-TX: 新会话 = **新图案流** (tx_lfsr 已回 SEED) ⇒ carry
                    //   必须一起清: 否则新流开头的 (8-k) 字节会是**旧会话**的残留
                    //   (与 pipe 残余字同族的那类"跨会话泄漏")。它是 carry 唯一的
                    //   会话边界清除点 —— 与本 if 同拍、同条件, 故"清了 carry" ⟺
                    //   "换了流" (ev_down→closing→idle 那条路不清, 但那条路之后
                    //   唯有 ev_up 能让 app 再发, 而 ev_up 一定会清; 见 §wb 论证)。
                    //   ⚠️ 构建 E (A3): 这条"新会话必清 carry"的理由**依赖 ev_up 一定
                    //   会被消费** —— 而被吞的 ev_up 现在由 up_pend_r 补做 ⇒ 该前提
                    //   从"脉冲不丢"变成"事件不丢"(更强), 论证仍成立。
                    wc_buf   <= 64'd0; wc_n <= 4'd0;
                    bad_frm  <= (i_bad_frame == 16'd1);
                end
            end
            if (ev_up) up_lat <= 1'b1;
            // ---- ⭐ 构建 E (A3): 待补事件的登记 / 消费 / 撤销 ----------------
            //   登记: ev_up 这一拍判据为假 (事件被吞) ⇒ 记住它 (槽号一起记);
            //   消费: `up_do` 那一拍清掉 (= 上面换流块已执行);
            //   撤销: 补做目标槽又来了一次 CONN_DOWN (新连接也关了) ⇒ 不再补
            //         (不撤销的话会把一个已经拆掉的连接当成活的重新发流)。
            //   ⚠️ 块序即优先级: 这三条都在换流块**之后**, 且互补 (up_do 与
            //      "ev_up && !up_ok" 结构性互斥) ⇒ up_pend_r 单一写者、无覆盖。
            if (up_do) up_pend_r <= 1'b0;
            else if (ev_up) begin
                up_pend_r  <= 1'b1;
                up_pend_id <= ev_slot;
            end
            if (ev_down && up_pend_r && (ev_slot == up_pend_id) && !ev_up)
                up_pend_r <= 1'b0;
            // W3 (P5a 复核): 对端关闭不能直接撤 pw_valid (AXIS 违约: 无 tlast、
            // 不等 m_tready 就撤) — 若恰在呈交期间 ev_down, tcp_tx_frame 会停在
            // S_RECV (该态 tready=1) 等下一位, 下一帧首字被当续载荷吞掉 ⇒ 帧边界
            // 错位且 app 不再呈现新帧时永久卡住。正确做法: 置收尾标志, 在下一个
            // m_tready 拍把**当前字节**以 tlast 收帧 (不推进 remain/LFSR 语义),
            // 然后回 idle。
            if (ev_down && active && (ev_slot == act_id)) begin
                closing <= 1'b1;
            end

            // ---- W3 收尾 ----
            // P5e: 换流撞车拍 (ev_restart) 由上面的 ev_up 块接管 (它撤字 + 发
            // close_send 的 0 载荷收尾字闭合本帧) ⇒ 本块让位, 否则同拍双写会把
            // 换流的赋值盖掉 (块序在 Verilog 里就是优先级: ev_up 块在前 ⇒ 必须
            // 显式让位, 不能靠先后)。
            if (closing && !ev_restart) begin
                if (pw_valid && !drop_pw) begin
                    // 已有字在呈交且本帧**有**载荷: m_tlast 组合含 closing -> 该字
                    // 带 tlast 被消费即闭合 (载荷 = 图案前缀, 逐字节判据不破)
                    if (m_tready) begin
                        pw_valid <= 1'b0; closing <= 1'b0; active <= 1'b0;
                        op_pend <= 1'b0; op_sent <= 1'b0;
                        stat_tx_frames <= stat_tx_frames + 32'd1;
                    end
                end else if (close_send) begin
                    // 0 载荷收尾字 (含 drop_pw 撤字拍): 帧器若已收下 opener 停在
                    // S_RECV, 这个 tlast 就是唯一出路
                    if (m_tready) begin
                        pw_valid <= 1'b0; closing <= 1'b0; active <= 1'b0;
                        op_pend <= 1'b0; op_sent <= 1'b0;
                        stat_tx_frames <= stat_tx_frames + 32'd1;
                    end
                end else begin
                    // 本帧尚无**任何字**交付 (op_sent=0 且 seg_sent=0; op_beat 被
                    // !closing 挡住 ⇒ 本拍不会摊开 opener): 帧器未开帧, 直接回
                    // idle, 不发空帧。
                    closing <= 1'b0; active <= 1'b0; op_pend <= 1'b0; op_sent <= 1'b0;
                end
            end

            // ---- TX 字装配 / 呈交 ----
            if (asm_go) begin
                if (need == 4'd0) begin
                    // 帧已发完 (seg_sent == seg_len): 收帧
                    stat_tx_frames <= stat_tx_frames + 32'd1;
                    if (bad_frm) stat_bad_frames <= stat_bad_frames + 32'd1;
                    frm_idx <= frm_idx + 16'd1;
                    bad_frm <= 1'b0;
                    if ((remain == 32'd0) && !CONT_OK) begin
                        active <= 1'b0;
                        done   <= 1'b1;
                        op_pend <= 1'b0; op_sent <= 1'b0;
                        if (AUTO_CLOSE) begin
                            close_req <= 1'b1;
                            close_id  <= act_id;
                        end
                    end else if (tx_ok) begin
                        // 下一帧长度 (坏帧注入: 第 i_bad_frame 帧)
                        bad_frm <= (i_bad_frame != 16'd0) &&
                                   ((frm_idx + 16'd1) == i_bad_frame);
                        seg_len <= ((i_bad_frame != 16'd0) &&
                                    ((frm_idx + 16'd1) == i_bad_frame)) ? BAD_LEN :
                                   ((remain_nxt > {20'b0, TX_SEGSZ}) ? TX_SEGSZ : remain_nxt[11:0]);
                        seg_sent <= 12'd0;
                        bcnt <= 4'd0;
                        // P5e: 新帧先发 0 载荷 opener (帧首字), 载荷等它落地
                        op_pend <= 1'b1; op_sent <= 1'b0;
                        // ⭐ 连续模式: 量子耗尽 ⇒ 重装载 (图案 LFSR 不动 ⇒ 线上无缝)
                        if (cont_reload) remain <= TX_BYTES;
                    end else begin
                        // P5d-D2: 连接不可发 (abort fence / 窗口关 / 拆连) ⇒ 不再
                        // 启动新帧。**本帧已完整交付** (上面 else-if 分支只在
                        // need==0 且 remain!=0 时到达), 故此刻 app 侧没有在飞字:
                        // pipe 里不会留下任何"下一帧首字"给新会话继承 —— D1 曝光
                        // 的 8B 循环移位/计数差 8/pat_done=0 三条的根因即此处。
                        // 静默等 tx_ok 恢复 (窗口重开) 或同槽新会话 (ev_up 重启)。
                        frm_wait <= 1'b1;
                    end
`ifdef P7B_10G
                end else if (wc_go) begin
                    // ⭐ P7B-GAP9-TX: **1 拍发射 need_a (1..8) 字节** (尾字不再走逐字节路)。
                    //   `wc_pw` 已是"左对齐 + 未用字节清 0"的字 (与 `ljust8(stg,need)`
                    //   同约定) ⇒ `pw_n = need_a` / `pw_keep = kmask8(need_a)` 与默认构建
                    //   在**同一个字**上逐位相同 (need_a ≡ 该字实际字节数)。
                    //   `pw_last` 用**前瞻** sent_a (与 a2 路同基准; 非前瞻会差一个字的
                    //   偏移 ⇒ 帧长恰为 8 倍数时末字丢 tlast)。
                    //   ⚠️ carry 与 LFSR 的写只在 `!bad_frm` 生效 (坏帧对图案流不可见);
                    //      case A (只吃 carry) **不推进 LFSR** (它一个字节都没从 LFSR 取)。
                    pw_data  <= wc_pw;
                    pw_keep  <= kmask8(need_a);
                    pw_n     <= need_a;
                    pw_last  <= ((sent_a + {8'b0, need_a}) >= seg_len);
                    pw_valid <= 1'b1;
                    bcnt     <= 4'd0;
                    stg      <= 64'd0;
                    if (!bad_frm) begin
                        wc_buf <= wc_nxt;
                        wc_n   <= wc_nnxt;
                        if (wc_b) tx_lfsr <= xs_next8(tx_lfsr);
                    end
                end else if (a2_ldw && !TAILC_OK) begin
                    // A2: **整字 1 拍装载** —— 8 个连续字节由常量 XOR 网 (xs_word8)
                    // 一拍产出, 与逐字节路径是**同一组映射** (M^0..M^7 的字节行);
                    // LFSR 同拍推进 8 步 (xs_next8 = M^8)。只在 need_a==8 时走 ⇒
                    // 尾字 (need_a<8) 结构性回落下面的逐字节路径。
                    // ⚠️ P7B-GAP9-TX: `&& !TAILC_OK` 是本轮**新增的常量门** ——
                    //    TAILC_OK=1 时这一支整条死掉 (need_a==8 ⟹ wc_go=1, 上面的
                    //    wc 路已接管整字; 常量 0 ⇒ 综合直接删掉这一段, 不付面积);
                    //    TAILC_OK=0 时它**逐字就是改动前的条件** (a2_ldw), 行为不变。
                    // pw_last 基准 = **前瞻 sent_a** (非前瞻会差一个字的偏移 ⇒ 帧
                    // 长度恰为 8 倍数时最后一个满字丢 tlast)。
                    pw_data  <= bad_frm ? 64'hA5A5A5A5A5A5A5A5 : xs_word8(tx_lfsr);
                    pw_keep  <= 8'hFF;
                    pw_n     <= 4'd8;
                    pw_last  <= ((sent_a + 12'd8) >= seg_len);
                    pw_valid <= 1'b1;
                    bcnt     <= 4'd0;
                    stg      <= 64'd0;
                    if (!bad_frm) tx_lfsr <= xs_next8(tx_lfsr);
                end else if (bcnt < need_a) begin
`else
                end else if (bcnt < need) begin
`endif
                    bcnt    <= bcnt + 4'd1;
                    stg     <= stg_n;
                    if (!bad_frm) tx_lfsr <= xs_next(tx_lfsr);
                end
            end
            // ---- P5d-D2: frm_wait 解除 (tx_ok 恢复 ⇒ 启动下一帧, 从 remain 续) ----
            // 与上面的帧启动门**同一组赋值** (只在 frm_wait 拍生效, 而 asm_go 在
            // frm_wait 拍恒 0 ⇒ 两者互斥, 不会同拍双写)。
            if (frm_wait && tx_ok) begin
                frm_wait <= 1'b0;
                bad_frm  <= (i_bad_frame != 16'd0) &&
                            ((frm_idx + 16'd1) == i_bad_frame);
                seg_len  <= ((i_bad_frame != 16'd0) &&
                             ((frm_idx + 16'd1) == i_bad_frame)) ? BAD_LEN :
                            ((remain_nxt > {20'b0, TX_SEGSZ}) ? TX_SEGSZ : remain_nxt[11:0]);
                seg_sent <= 12'd0;
                bcnt     <= 4'd0;
                op_pend  <= 1'b1; op_sent <= 1'b0;   // P5e: 同样以 opener 起帧
                // ⭐ 连续模式: 量子耗尽 ⇒ 重装载 (与 tx_ok 臂同一件事, 两处都要有)
                if (cont_reload) remain <= TX_BYTES;
            end
            // ---- P5e: opener 交付 (帧首字落地 = 帧已"预开") ----
            // 交付判据与载荷字同一条 (pw_valid && m_tready 的镜像): m_tready 就是
            // axis_pipe 的 s_ready ⇒ 该拍 pipe 会把这个 0 载荷字装进它的 1 深寄存器。
            // op_pend 清掉后 m_tvalid 转为载荷字 (组合输出, 无空拍; 载荷装配要 8 拍,
            // 期间 m_tvalid=0 是正常的 —— 帧器此时在 S_IDLE 等帧首字)。
            if (op_beat && m_tready) begin
                op_pend <= 1'b0;
                op_sent <= 1'b1;
            end
            // 字齐 -> 呈交 (1 拍后 valid)
            if (asm_full && !pw_valid) begin
                pw_data  <= ljust8(stg, need);
                pw_keep  <= kmask8(need);
                pw_n     <= need;
                pw_last  <= ((seg_sent + {8'b0, need}) >= seg_len);
                pw_valid <= 1'b1;
                bcnt     <= 4'd0;
                stg      <= 64'd0;
            end
            // 呈交消费 (AXIS: tready=0 期间 pw_* 保持; m_* 组合输出)
            // W3: closing 期间由上面的收尾分支独占消费 (不推进 remain/LFSR)
            if (pw_valid && m_tready && !closing) begin
                pw_valid <= 1'b0;
                seg_sent <= seg_sent + {8'b0, pw_n};
                // 注入的超长帧不计入 TX_BYTES 计划 (被 RTL 丢弃, 不上线):
                // remain/stat_tx_bytes 都不动, 图案流位置不变 (LFSR 也冻结)
                if (!bad_frm) begin
                    remain <= (remain >= {20'b0, pw_n}) ? (remain - {20'b0, pw_n}) :
                              32'd0;
                    stat_tx_bytes <= stat_tx_bytes + {28'b0, pw_n};
                end
            end
`ifdef P7B_10G
            // ---- A2: 同拍"消费 + 预取" ⇒ **装载赢 pw_valid** -------------------
            // 同一个 always 块内对同一变量多次非阻塞赋值 = 后者胜。上面消费块的
            // `pw_valid <= 1'b0` 会把**本拍刚预取的字**丢掉 (每字丢一个字 ⇒ 字节流
            // 整段错位) ⇒ 必须在它之后把 pw_valid 写回 1 (只有真装载了才写;
            // a2_ldw 已含 !a2_hold ⇒ 换流/收尾拍不复活)。
            // ⭐ P7B-GAP9-TX: TAILC_OK=1 时装载者是 `wc_go` (整字/尾字同一条路);
            //    TAILC_OK=0 时**逐字就是改动前的 `if (a2_ldw)`** (常量短路已证)。
            if (wc_go || (a2_ldw && !TAILC_OK)) pw_valid <= 1'b1;
`endif

            // ---- RX 取值/比对 ----
            if (rxs == 2'd0) begin
                if (rx_tvalid) begin
                    rw_data <= rx_tdata;
                    rw_keep <= rx_tkeep;
                    rw_n    <= pop8(rx_tkeep);
                    rw_i    <= 4'd0;
`ifdef P7B_10G
                    if (rx_wide) begin
                        // 满字: 一拍比完 8 lane (rxs 保持 0 ⇒ 下一拍立刻收下一个字)。
                        // 与串行路径同口径: 每字节记一次 (失配按 lane 数量记)。
                        stat_mismatch <= stat_mismatch + {28'b0, rx_bad_n};
                        stat_rx_bytes <= stat_rx_bytes + 32'd8;
                        rx_lfsr       <= rx_lfsr_8;
                    end else if (pop8(rx_tkeep) == 4'd0) begin
`else
                    if (pop8(rx_tkeep) == 4'd0) begin
`endif
                        // 零有效字节 (空尾字): 直接完成
                        rxs <= 2'd0;
                    end else begin
                        rxs <= 2'd1;
                    end
                end
            end else begin
                if (byte_at(rw_data, rw_i) != rx_exp)
                    stat_mismatch <= stat_mismatch + 32'd1;
                rx_lfsr <= xs_next(rx_lfsr);
                stat_rx_bytes <= stat_rx_bytes + 32'd1;
                if (rw_i + 4'd1 >= rw_n) rxs <= 2'd0;
                else                      rw_i <= rw_i + 4'd1;
            end

            // ---- ⭐ P7B-GAP9-TX: 两个停滞计数器 (**判别器**, 语义逐字如下) --------
            // 动机 (设计件 §D): 板级 `P ≈ 199.7` 拍/帧 相对线几何 193 多出的 ~6.7 拍
            //   到底是"窗口/信用停顿"、"帧器背压"还是 app 自身的残余开销 —— 纸面算不出
            //   来 (预算里没有对端模型)。这两个计数器与 `ΔW43/ΔW20` 同窗采样即可**分离**。
            // 两条语义 (拍数, 不是事件数; 按**当拍寄存器态**判, 与其它 stat_* 同口径):
            //   stat_frmwait_cyc: 计数 ⟺ `frm_wait == 1 && active == 1 && !bad_frm`
            //     = "本帧**已完整交付**, 但在等 app_ctrl 的 tx_ok 门 (app_tx_ready)"。
            //     · 置位拍**不算** (那拍 frm_wait 仍是 0): 置位发生在收帧拍 (need==0) 且
            //       tx_ok==0 时, 即 `frm_wait <= 1` 的那个沿; 计数从**下一拍**开始。
            //     · 解除拍**算**: `frm_wait && tx_ok` 那拍 frm_wait 仍是 1 (它在沿后才落 0)。
            //     · `active == 0` **不算**: 会话已拆 (ev_down) 后 frm_wait 可能残留 1
            //       (W3 收尾不清它) —— 那是空闲态, 不是信用停顿, 混进来会把这个量变成
            //       "挂住时长"而失去判别力。
            //     · `bad_frm` **不算** (显式写出): 注入的超长帧不是业务帧。实测二者
            //       结构性互斥 (收帧拍 `bad_frm <= 1'b0` 与 `frm_wait <= 1'b1` 同拍写
            //       ⇒ frm_wait=1 期间 bad_frm 恒 0), 这里显式保留该项是**防将来改动**
            //       破坏该性质 (不让它静默变成"混进注入帧的拍数")。
            //     · 复位态 frm_wait=0 ⇒ 结构性不算。
            //   stat_bp_cyc: 计数 ⟺ `pw_valid == 1 && m_tready == 0 && !closing && !bad_frm`
            //     = "app 有字要交给帧器, 但帧器 (经 axis_pipe) 不收"。
            //     · 复位态 pw_valid=0 ⇒ 不算; `closing` 期间的呈交口归 W3 收尾独占,
            //       那类停顿**既不是窗口停顿也不是帧器背压** ⇒ 两个计数器都不计
            //       (这是**登记过的盲区**, 判读时不许把它算进任一侧)。
            //     · `bad_frm` 同上显式排除 (板级 `i_bad_frame ≡ 0` ⇒ 与字面定义逐位等价)。
            //   ⚠️ 两个都是 32 位**自然回卷**计数器 (与 stat_tx_bytes 同族): 156.25 MHz 下
            //      2^32 拍 = **27.487 s** ⇒ 判据必须 mod 2^32 **且同时记原始值** (全局 #55)。
            if (frm_wait && active && !bad_frm)
                stat_frmwait_cyc <= stat_frmwait_cyc + 32'd1;
            if (pw_valid && !m_tready && !closing && !bad_frm)
                stat_bp_cyc <= stat_bp_cyc + 32'd1;

            // ---- 活动/指示灯 ----
            if ((rx_tvalid && rx_tready) || (pw_valid && m_tready) || asm_go)
                act_tmr <= ACT_TMR_INIT;
            else if (act_tmr != 20'd0)
                act_tmr <= act_tmr - 20'd1;
            led_r[0] <= up_lat;
            led_r[1] <= (act_tmr != 20'd0);
            if (stat_mismatch != 32'd0) led_r[2] <= 1'b1;
            led_r[3] <= done;
        end
    end

    // rx_tlast / rx_tid / rw_keep: 本阶段只做字节流比对, 帧尾/连接号未消费
    // (P5b 的 RX 消费模型会用到)
endmodule
